def eval_modules(html):
    m = re.search(r"\n  modules\(\) \{\n(.*?)\n  \}\n\n  upcoming\(\)", html, re.S)
    if not m:
        sys.exit('modules() bloğu bulunamadı')
    js = 'const modules=function(){\n' + m.group(1) + '\n};process.stdout.write(JSON.stringify(modules()));'
    with tempfile.NamedTemporaryFile('w', suffix='.js', delete=False, encoding='utf-8') as f:
        f.write(js)
        path = f.name
    try:
        res = subprocess.run(['node', path], capture_output=True, text=True, check=True)
    finally:
        os.unlink(path)
    return json.loads(res.stdout)


def order(seed, n):
    """Atlas-Kitap.dc.html _order(): quiz seçeneklerinin deterministik karışımı. Basılı sürümde seed = soru indeksi + 10 × bölüm no
    (web kitabında seed = soru indeksi; her bölümde aynı harf deseni çıktığı için basılıda bölüme göre değişir)."""
    arr = list(range(n))
    r = (seed + 3) * 2654435761 % 2147483647
    for i in range(n - 1, 0, -1):
        r = (r * 16807) % 2147483647
        j = r % (i + 1)
        arr[i], arr[j] = arr[j], arr[i]
    return arr


STR_RE = re.compile(r"'((?:[^'\\\n]|\\.)*)'|\"((?:[^\"\\\n]|\\.)*)\"|`((?:[^`\\]|\\.)*)`", re.S)
CSSY = re.compile(r"\d+px|rgba?\(|#[0-9a-fA-F]{3,6}\b|font-|transition|margin|padding|border|display:|width:|height:"
                  r"|linear-gradient|flex|cursor|opacity:|letter-spacing|text-transform|position:|overflow")


def unescape(s):
    s = re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), s)
    return s.replace("\\'", "'").replace('\\"', '"').replace('\\n', ' ').replace('\\\\', '\\')


def embedded_texts(html):
    """renderVals() içindeki demo dallarından, UI etiketi olmayan uzun metin sabitlerini çıkarır."""
    start = html.index('\n  renderVals() {')
    end = html.index('\n  _order(', start)
    region = html[start:end]
    marks = [(m.start(), m.group(1)) for m in re.finditer(r"demo\.type === '([a-z0-9]+)'", region)]
    quiz_at = region.find('// shuffle deterministically')
    result = {}
    for i, (pos, typ) in enumerate(marks):
        nxt = marks[i + 1][0] if i + 1 < len(marks) else (quiz_at if quiz_at > pos else len(region))
        chunk = region[pos:nxt]
        found = []
        for m in STR_RE.finditer(chunk):
            s = unescape(next(g for g in m.groups() if g is not None)).strip()
            if len(s) < 18 or ' ' not in s or not re.search(r'[A-Za-zçğıöşüÇĞİÖŞÜ]', s):
                continue
            if CSSY.search(s) or s.startswith('${'):
                continue
            if s not in found:
                found.append(s)
        if found:
            result.setdefault(typ, []).extend(x for x in found if x not in result.get(typ, []))
    return result


# ---------------------------------------------------------------- markdown yardımcıları

def md_table(rows, cols=None):
    if not rows:
        return ''
    if cols is None:
        cols = []
        for r in rows:
            for k in r:
                if k not in cols:
                    cols.append(k)
    esc = lambda v: str(v).replace('|', '\\|').replace('\n', ' ')
    out = ['| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)]
    for r in rows:
        out.append('| ' + ' | '.join(esc(r.get(c, '')) if isinstance(r, dict) else esc(r) for c in cols) + ' |')
    return '\n'.join(out)


def render_data(demo):
    """Demo nesnesindeki veri alanlarını (types, items, rules, matrix …) Markdown'a çevirir."""
    skip = {'type', 'title', 'hint', 'hintBasit', 'neOluyor', 'neOluyorBasit'}
    parts = []
    for k, v in demo.items():
        if k in skip:
            continue
        if isinstance(v, list) and v and all(isinstance(x, dict) for x in v):
            parts.append(f'**{k}**\n\n' + md_table(v))
        elif isinstance(v, list) and v and all(isinstance(x, list) for x in v):
            parts.append(f'**{k}**\n\n' + md_table([{str(i): c for i, c in enumerate(row)} for row in v]))
        elif isinstance(v, list):
            parts.append(f'**{k}**: ' + ', '.join(str(x) for x in v))
        elif isinstance(v, dict):
            parts.append(f'**{k}**: ' + ', '.join(f'{a}={b}' for a, b in v.items()))
        else:
            parts.append(f'**{k}**: {v}')
    return '\n\n'.join(parts)


