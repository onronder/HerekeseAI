TR_MAP = str.maketrans('çğıöşüÇĞİÖŞÜâîû', 'cgiosuCGIOSUaiu')


def slug(s):
    s = s.translate(TR_MAP).lower()
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    return s


