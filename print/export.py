def module_md(lang, mod, mi, emb):
    t = T[lang]
    n = int(mod['n'])
    L = []
    L.append(f"# {mod['n']} · {mod['tag']} — {mod['title']}")
    L.append(f"_{mod['subtitle']}_ · {t['accent']} `{mod['acc']}`")
    L.append('')
    L.append(f"<!-- {t['generated']} ({date.today().isoformat()}). {t['lang_note']} -->")
    L.append(f"<!-- {t['legend']} -->")
    L.append('')
    fig = 0
    for si, sec in enumerate(mod['sections']):
        is_quiz = bool(sec.get('quiz'))
        L.append(f"## {n}.{si + 1} {sec['h2']}")
        link = f"{LIVE[lang]}{SLUGS.get(lang, {}).get(f'{n}.{fig + 1}', '?')}" if sec.get('demo') else '-'

        L.append(f"`id: {sec['id']}` · `{sec['label']}` · {t['live']}: <{link}>")
        L.append('')
        if is_quiz:
            L.append(f"_{t['answers']}: {t['answers_file']}_")
            L.append('')
            for qi, q in enumerate(sec['quiz']):
                L.append(f"{qi + 1}. {q['q']}")
                for pos, oi in enumerate(order(qi * 7 + 13 * int(mod["n"]) + 5, len(q["opts"]))):
                    L.append(f"   {chr(97 + pos)}) {q['opts'][oi]}")
                L.append('')
            continue
        if sec.get('tip'):
            L.append(f"> **{t['margin']}.** {sec['tip']}")
            L.append('')
        L.append(f"### {t['simple']}")
        L.append('')
        for p in sec.get('basit', []):
            L.append(p)
            L.append('')
        L.append(f"### {t['tech']}")
        L.append('')
        for p in sec.get('teknik', []):
            L.append(p)
            L.append('')
        demo = sec.get('demo')
        if demo:
            fig += 1
            kind = DEMO_KIND.get(demo['type'], '?')
            L.append(f"### {t['figure']} {n}.{fig} — {demo['title']}")
            L.append(f"`demo: {demo['type']}` · {t['kind']} **{kind}**")
            L.append('')
            hint = demo.get('hintBasit') or demo.get('hint', '')
            L.append(f"**{t['setup']}** — _{t['todo']}_  ")
            L.append(f"_{t['hint']}: {hint}_")
            L.append('')
            L.append(f"**{t['steps']}** — _{t['todo']}_")
            L.append('')
            L.append(f"**{t['what_s']}** — {demo.get('neOluyorBasit', demo.get('neOluyor', ''))}")
            L.append('')
            L.append(f"**{t['what_t']}** — {demo.get('neOluyor', '')}")
            L.append('')
            L.append(f"**{t['try_']}** — _{t['todo']}_ · QR → <{link}>")
            L.append('')
            data = render_data(demo)
            if data:
                L.append(f"<details><summary>{t['data']}</summary>")
                L.append('')
                L.append(data)
                L.append('')
                L.append('</details>')
                L.append('')
            texts = emb.get(demo['type'])
            if texts:
                L.append(f"**{t['embedded']}**")
                L.append('')
                for s in texts:
                    L.append(f"- {s}")
                L.append('')
        L.append(f"_{t['bridge']}: {t['todo']}_")
        L.append('')
    L.append(f"## {t['takeaways']}")
    L.append('')
    L.append(f"_{t['takeaways_todo']}_")
    L.append('')
    return '\n'.join(L)


def answer_key_md(lang, data):
    t = T[lang]
    L = [f"# {t['key_title']}", '', f"<!-- {t['generated']} ({date.today().isoformat()}); elle düzenlenmez. -->", '',
         f"## {t['key_quiz']}", '']
    for mod in data:
        n = int(mod['n'])
        for si, sec in enumerate(mod['sections']):
            if not sec.get('quiz'):
                continue
            L.append(f"### {mod['n']} · {mod['title']}")
            L.append('')
            for qi, q in enumerate(sec['quiz']):
                o = order(qi * 7 + 13 * int(mod["n"]) + 5, len(q["opts"]))
                letter = chr(97 + o.index(0))
                L.append(f"{n}.{si + 1} / {qi + 1}: **{letter}** · {q['opts'][0]}")
                L.append('')  # her cevap ayrı paragraf (uzun tire yok: stil kılavuzu)
    L.append(f"## {t['key_self']}")
    L.append('')
    for mod in data:
        n = int(mod['n'])
        fig = 0
        for sec in mod['sections']:
            demo = sec.get('demo')
            if not demo:
                continue
            fig += 1
            if demo['type'] == 'classify':
                cats = demo.get('cats') or [demo['catA'], demo['catB']]
                lab = {c['key']: c['label'] for c in cats}
                L.append(f"### {t['figure']} {n}.{fig} — {demo['title']}")
                L.append('')
                L.append(md_table([{'#': i + 1, 'item': it['label'], 'answer': lab.get(it['cat'], it['cat'])}
                                   for i, it in enumerate(demo['items'])]))
                L.append('')
            elif demo['type'] in SELF_TEST_EMBEDDED:
                L.append(f"### {t['figure']} {n}.{fig} — {demo['title']}")
                L.append('')
                L.append(f"_{t['todo']}: {t['key_manual']}_")
                L.append('')
    return '\n'.join(L)


def embedded_md(lang, data, emb):
    t = T[lang]
    L = [f"# {t['emb_title']}", '', f"<!-- {t['generated']} ({date.today().isoformat()}); elle düzenlenmez. -->", '']
    total = 0
    for mod in data:
        n = int(mod['n'])
        fig = 0
        for sec in mod['sections']:
            demo = sec.get('demo')
            if not demo:
                continue
            fig += 1
            texts = emb.get(demo['type'], [])
            L.append(f"## {t['figure']} {n}.{fig} — {demo['title']} (`{demo['type']}`)")
            L.append('')
            if not texts:
                L.append(t['none'])
            for s in texts:
                L.append(f"- {s}")
                total += len(s)
            L.append('')
    L.insert(3, f"_{sum(len(v) for v in emb.values())} parça · {total} karakter_")
    return '\n'.join(L)


