def export(lang, force):
    t = T[lang]
    html = open(SOURCES[lang], encoding='utf-8').read()
    data = eval_modules(html)
    emb = embedded_texts(html)
    out = os.path.join(OUT, lang)
    os.makedirs(out, exist_ok=True)

    with open(os.path.join(out, 'book.json'), 'w', encoding='utf-8') as f:
        json.dump({'lang': lang, 'source': os.path.basename(SOURCES[lang]), 'modules': data, 'embedded': emb},
                  f, ensure_ascii=False, indent=1)

    written, kept = [], []
    for mi, mod in enumerate(data, 1):
        path = os.path.join(out, f"M{mod['n']}-{slug(mod['title'])}.md")
        if os.path.exists(path) and not force:
            kept.append(os.path.basename(path))
            continue
        with open(path, 'w', encoding='utf-8') as f:
            f.write(module_md(lang, mod, mi, emb))
        written.append(os.path.basename(path))

    with open(os.path.join(out, t['answers_file']), 'w', encoding='utf-8') as f:
        f.write(answer_key_md(lang, data))
    with open(os.path.join(out, t['embedded_file']), 'w', encoding='utf-8') as f:
        f.write(embedded_md(lang, data, emb))

    n_sec = sum(len(m['sections']) for m in data)
    n_demo = sum(1 for m in data for s in m['sections'] if s.get('demo'))
    n_quiz = sum(len(s.get('quiz', [])) for m in data for s in m['sections'])
    print(f"[{lang}] {len(data)} modül, {n_sec} bölüm, {n_demo} demo, {n_quiz} quiz sorusu, "
          f"{sum(len(v) for v in emb.values())} gömülü metin parçası")
    print(f"      yazıldı: {', '.join(written) or '-'}")
    if kept:
        print(f"      korundu (--force ile yenilenir): {', '.join(kept)}")
    print(f"      {t['deep_link_note']}")


if __name__ == '__main__':
    force = '--force' in sys.argv
    langs = ['tr', 'en']
    if '--lang' in sys.argv:
        langs = [sys.argv[sys.argv.index('--lang') + 1]]
    for lang in langs:
        export(lang, force)
